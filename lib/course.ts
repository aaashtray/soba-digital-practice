export const isCorrect = (q: Question, selected: number[]) =>
  selected.length === q.answer.length &&
  q.answer.every((a, i) => selected[i] === a);
export const isComplete = (q: Question, selected: number[]) =>
  selected.length === q.answer.length &&
  selected.every((x) => Number.isInteger(x) && x >= 0 && x < q.options.length);
